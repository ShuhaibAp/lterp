import PoHeader from "@/components/PoHeader";
import PickupEditor from "@/components/pickup/PickupEditor";
import PickupSummary from "@/components/pickup/PickupSummary";
import ReportCard from "@/components/pickup/ReportCard";
import StartPickup from "@/components/pickup/StartPickup";
import shared from "@/components/workflow.module.css";
import { requireRole } from "@/lib/dal";
import { formatDate } from "@/lib/po-constants";
import { getPickupRequest } from "@/lib/pickup";
import { getPurchaseOrder } from "@/lib/purchase-orders";

export const metadata = { title: "Pickup Request" };

const FLASH = {
  generated: "Inspection Report generated. The PO has moved to the Operations stage.",
};

export default async function PickupPage({ params, searchParams }) {
  const user = await requireRole("BD Team", "Admin", "Operations Team", "Factory Team");
  const { id } = await params;
  const flags = await searchParams;
  const [po, data] = await Promise.all([getPurchaseOrder(id), getPickupRequest(id)]);
  const p = data.pickup;
  const isBd = user.role === "BD Team";
  const isAdmin = user.role === "Admin";
  const flash = Object.keys(FLASH).find((key) => flags[key]);

  let body;
  if (!p) {
    if (!data.canStart) {
      body = (
        <div className={shared.card}>
          <p className={shared.text}>
            The pickup request becomes available once the client approves the quotation.
          </p>
        </div>
      );
    } else if (isBd) {
      body = <StartPickup poId={id} />;
    } else {
      body = (
        <div className={shared.card}>
          <p className={shared.text}>The BD team has not started the pickup request for this PO yet.</p>
        </div>
      );
    }
  } else if (p.editable && isBd) {
    body = <PickupEditor poId={id} pickup={p} />;
  } else {
    body = (
      <>
        {p.editable && isAdmin && <div className={shared.info}>The BD team is preparing this pickup request.</div>}
        {p.generatedAt && (
          <div className={shared.notice}>
            Generated by {p.generatedBy} on {formatDate(p.generatedAt)}.
          </div>
        )}
        <ReportCard poId={id} unlocked={p.canDownload} />
        <PickupSummary pickup={p} />
      </>
    );
  }

  return (
    <>
      <PoHeader po={po} tab="pickup" role={user.role} />
      {flash && <div className={shared.notice}>{FLASH[flash]}</div>}
      {body}
    </>
  );
}
