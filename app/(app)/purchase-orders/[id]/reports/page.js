import PoHeader from "@/components/PoHeader";
import ReportsPanel from "@/components/closeout/ReportsPanel";
import styles from "@/components/closeout/closeout.module.css";
import shared from "@/components/workflow.module.css";
import { requireRole } from "@/lib/dal";
import { getFinalReports } from "@/lib/closeout";
import { formatDate } from "@/lib/po-constants";
import { getPurchaseOrder } from "@/lib/purchase-orders";

export const metadata = { title: "Final Reports — Cynosure MIS" };

export default async function ReportsPage({ params, searchParams }) {
  const user = await requireRole("BD Team", "Admin", "Operations Team", "Factory Team");
  const { id } = await params;
  const flags = await searchParams;
  const [po, state] = await Promise.all([getPurchaseOrder(id), getFinalReports(id)]);
  const isAdmin = user.role === "Admin";

  return (
    <>
      <PoHeader po={po} tab="reports" role={user.role} />
      {flags.generated && <div className={shared.notice}>The final reports have been generated.</div>}

      {state.generated ? (
        <div className={shared.card}>
          <h2 className={shared.cardTitle}>Final reports</h2>
          <p className={shared.text}>
            Generated by {state.generatedBy} on {formatDate(state.generatedAt)}. Each document opens as a PDF you can
            download or print.
          </p>
          <ul className={styles.docs}>
            {state.documents.map((d) => (
              <li key={d.kind} className={styles.docRow}>
                <span>{d.title}</span>
                <a className={shared.btn} href={`/purchase-orders/${id}/reports/${d.kind}`} target="_blank" rel="noreferrer">
                  Open PDF
                </a>
              </li>
            ))}
          </ul>
        </div>
      ) : isAdmin ? (
        <ReportsPanel poId={id} state={state} />
      ) : (
        <div className={shared.card}>
          <div className={`${styles.result} ${styles.pending}`}>Not generated yet</div>
          <p className={shared.text}>
            Admin generates the final reports once Operations and Factory are complete and the weighment cross-check is
            resolved.
          </p>
          {state.blockers.length > 0 && (
            <div className={shared.remaining}>
              Still waiting on:
              <ul>
                {state.blockers.map((b) => (
                  <li key={b}>{b}</li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}
    </>
  );
}
